export const SUFIXOS_ESTAGIO = ["","_exposed","_weathered","_oxidized"];
export const PECAS = ["helmet","chestplate","leggings","boots"];
const VANILLA_NO_ESTAGIO_0 = ["leather","copper","turtle","chainmail","iron","golden","diamond","netherite"];

// Identificador do item de uma peça (mesma regra do gerador).
export function idDaPeca(conjunto, peca, estagio = 0, carregado = false) {
  const chave = PECAS[peca];
  if (VANILLA_NO_ESTAGIO_0.includes(conjunto) && estagio === 0 && !carregado) return `minecraft:${conjunto}_${chave}`;
  return `hydro:${conjunto}_${chave}${SUFIXOS_ESTAGIO[estagio]}${carregado ? "_charged" : ""}`;
}
